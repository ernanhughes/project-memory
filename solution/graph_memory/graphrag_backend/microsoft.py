"""Microsoft GraphRAG behind the StructuredMemoryBackend boundary.

All interaction goes through the versioned ``graphrag`` CLI (index/query)
plus reads of its parquet output. Nothing here imports graphrag internals,
so a package upgrade, a different implementation, or a purpose-built graph
can replace this module without touching callers.

Derived state is disposable and rebuildable; the source corpus is
authoritative. Index outputs live under the configured project root, which
is git-ignored work state — only manifests, exported snapshots, and run
records are committed.
"""

